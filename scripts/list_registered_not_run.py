"""List every protocol or registration whose status says it was registered but
never run, in one page.  Scans JSON files for a top-level or nested "status"
field containing "registered" together with "not_run"/"not run"/"unrun", and
markdown files for the literal token `registered_not_run`.

Usage: python scripts/list_registered_not_run.py [--out docs/REGISTERED_NOT_RUN.md]
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP_DIRS = {".git", ".venv", "node_modules", "__pycache__", ".pytest_cache"}
STATUS_RE = re.compile(r"registered[_ -]?(but[_ -])?not[_ -]?run|registered_not_run|unrun|not_yet_run", re.I)


def find_status(obj, hits: list, path: str = "") -> None:
    if isinstance(obj, dict):
        for k, v in obj.items():
            if isinstance(v, str) and k.lower() in ("status", "run_status", "execution_status", "state") and STATUS_RE.search(v):
                hits.append((path + "/" + k, v))
            else:
                find_status(v, hits, path + "/" + k)
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            find_status(v, hits, f"{path}[{i}]")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "REGISTERED_NOT_RUN.md"))
    args = ap.parse_args()
    rows = []
    for dirpath, dirnames, filenames in os.walk(ROOT):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for f in filenames:
            fp = os.path.join(dirpath, f)
            rel = os.path.relpath(fp, ROOT).replace(os.sep, "/")
            if f.lower().endswith(".json"):
                try:
                    with open(fp, "r", encoding="utf-8") as fh:
                        data = json.load(fh)
                except Exception:
                    continue
                hits: list = []
                find_status(data, hits)
                for where, val in hits:
                    pid = data.get("protocol_id") if isinstance(data, dict) else None
                    rows.append((rel, where, val, pid or ""))
            elif f.lower().endswith(".md"):
                try:
                    with open(fp, "r", encoding="utf-8", errors="replace") as fh:
                        text = fh.read()
                except Exception:
                    continue
                for m in re.finditer(r"`registered_not_run`", text):
                    line = text.count("\n", 0, m.start()) + 1
                    rows.append((rel, f"line {line}", "registered_not_run", ""))
    rows.sort()
    lines = ["# Registered but not run", "",
             "Generated by `scripts/list_registered_not_run.py`: every JSON status field that says a",
             "protocol or run was registered and not executed, plus every markdown mention of the",
             "literal token. A reader who sees \"registered\" elsewhere should check here before",
             "treating it as \"done\".", "",
             f"Entries: {len(rows)}", "",
             "| file | where | status | protocol_id |", "|---|---|---|---|"]
    for rel, where, val, pid in rows:
        lines.append(f"| [{rel}]({'../' + rel}) | {where} | `{val}` | {pid} |")
    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"{len(rows)} entries; wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
