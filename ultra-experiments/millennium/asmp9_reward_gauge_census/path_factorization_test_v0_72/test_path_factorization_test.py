from __future__ import annotations

from math import isclose

import sympy as sp

from path_factorization_test import (
    analyze_geometry,
    canonical_fixture,
    chi_square_test_design,
    df1_power_high_precision,
    exact_distance_squared,
    minimum_equal_repeats,
    noncentrality,
    weighted_residual_statistic,
)


def test_complete_fixture_identifies_and_falsifies() -> None:
    design, _ = canonical_fixture()
    geometry = analyze_geometry(design)
    assert geometry.design_rank == 3
    assert geometry.reward_coordinates_identified
    assert geometry.factorization_test_available
    assert geometry.residual_degrees_of_freedom == 1
    assert geometry.primitive_contrasts == ((1, -1, -1, 1),)


def test_interaction_distance_is_one_quarter() -> None:
    design, mean = canonical_fixture()
    assert exact_distance_squared(design, mean) == sp.Rational(1, 4)


def test_dropping_one_path_keeps_identification_but_kills_test() -> None:
    design, _ = canonical_fixture()
    reduced = design[:3, :]
    geometry = analyze_geometry(reduced)
    assert geometry.reward_coordinates_identified
    assert geometry.residual_degrees_of_freedom == 0
    assert not geometry.factorization_test_available
    assert geometry.primitive_contrasts == tuple()


def test_equal_variance_noncentrality_matches_exact_distance() -> None:
    design, mean = canonical_fixture()
    means = [float(value) for value in mean]
    # n=8 repeats with unit sample variance gives mean variance 1/8.
    value = noncentrality(design, means, [1 / 8] * 4)
    assert isclose(value, 2.0, rel_tol=0, abs_tol=1e-12)


def test_minimum_repeats_is_32_for_frozen_gate() -> None:
    result = minimum_equal_repeats(
        distance_squared=0.25,
        sample_variance=1.0,
        degrees_of_freedom=1,
        alpha=0.05,
        target_power=0.80,
    )
    assert result["minimum_repeats_per_path"] == 32
    assert result["power"] >= 0.80
    assert result["previous_power"] < 0.80


def test_chi_square_power_matches_minimum_repeat_cell() -> None:
    design = chi_square_test_design(1, 0.05, 8.0)
    assert isclose(design["critical_value"], 3.841458820694124)
    assert isclose(design["power"], 0.8074304194325571)


def test_high_precision_boundary_independently_brackets_target() -> None:
    power_31 = df1_power_high_precision(
        alpha="0.05", noncentrality_value="7.75"
    )
    power_32 = df1_power_high_precision(
        alpha="0.05", noncentrality_value="8"
    )
    assert float(power_31) < 0.80
    assert float(power_32) > 0.80
    assert isclose(float(power_31), 0.7950080284018122)
    assert isclose(float(power_32), 0.8074304194325571)


def test_null_mean_has_zero_statistic() -> None:
    design, _ = canonical_fixture()
    # These means are generated by rewards (1,2,3).
    means = [1.0, 2.0, 4.0, 5.0]
    result = weighted_residual_statistic(design, means, [0.1] * 4)
    assert isclose(result["statistic"], 0.0, abs_tol=1e-12)
    assert result["degrees_of_freedom"] == 1
