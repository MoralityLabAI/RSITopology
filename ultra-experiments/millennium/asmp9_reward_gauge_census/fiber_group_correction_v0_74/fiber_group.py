"""Finite fiber-group correction for ASMP-9 v0.74."""

from __future__ import annotations

from dataclasses import dataclass
from itertools import combinations
from math import factorial
from typing import Hashable, Iterable, Sequence


Permutation = tuple[int, ...]
Labels = tuple[Hashable, ...]


def validate_permutation(permutation: Permutation, size: int) -> None:
    if len(permutation) != size or set(permutation) != set(range(size)):
        raise ValueError("invalid permutation")


def compose(left: Permutation, right: Permutation) -> Permutation:
    """Return ``left after right``."""

    if len(left) != len(right):
        raise ValueError("permutations have different sizes")
    return tuple(left[right[index]] for index in range(len(left)))


def generated_group(size: int, generators: Sequence[Permutation]) -> frozenset[Permutation]:
    """Enumerate the finite permutation group generated by ``generators``."""

    identity = tuple(range(size))
    for generator in generators:
        validate_permutation(generator, size)
    group = {identity}
    frontier = [identity]
    while frontier:
        current = frontier.pop()
        for generator in generators:
            for candidate in (
                compose(generator, current),
                compose(current, generator),
            ):
                if candidate not in group:
                    group.add(candidate)
                    frontier.append(candidate)
    return frozenset(group)


def canonical_partition(blocks: Iterable[Iterable[int]]) -> tuple[tuple[int, ...], ...]:
    return tuple(
        sorted(
            (tuple(sorted(block)) for block in blocks),
            key=lambda block: (block[0], len(block), block),
        )
    )


def label_partition(labels: Labels) -> tuple[tuple[int, ...], ...]:
    blocks: dict[Hashable, list[int]] = {}
    for index, label in enumerate(labels):
        blocks.setdefault(label, []).append(index)
    return canonical_partition(blocks.values())


def orbit_partition(
    size: int,
    generators: Sequence[Permutation],
) -> tuple[tuple[int, ...], ...]:
    group = generated_group(size, generators)
    unseen = set(range(size))
    blocks = []
    while unseen:
        seed = min(unseen)
        orbit = {permutation[seed] for permutation in group}
        blocks.append(orbit)
        unseen -= orbit
    return canonical_partition(blocks)


def full_fiber_group_size(observation: Labels) -> int:
    """Order of Aut(O): the product of symmetric groups on O's fibers."""

    result = 1
    for block in label_partition(observation):
        result *= factorial(len(block))
    return result


def aggregate_observation(queries: Sequence[Labels]) -> Labels:
    if not queries:
        raise ValueError("at least one query is required for aggregation")
    size = len(queries[0])
    if any(len(query) != size for query in queries):
        raise ValueError("query sizes differ")
    return tuple(tuple(query[index] for query in queries) for index in range(size))


@dataclass(frozen=True)
class AccessDiagnostic:
    status: str
    gauge_orbits: tuple[tuple[int, ...], ...]
    observation_fibers: tuple[tuple[int, ...], ...]
    gauge_split_witnesses: tuple[tuple[int, int], ...]
    unseparated_non_gauge_pairs: tuple[tuple[int, int], ...]


def diagnose_access(
    queries: Sequence[Labels],
    generators: Sequence[Permutation],
    *,
    size: int | None = None,
) -> AccessDiagnostic:
    if queries:
        inferred_size = len(queries[0])
        if any(len(query) != inferred_size for query in queries):
            raise ValueError("query sizes differ")
        if size is not None and size != inferred_size:
            raise ValueError("declared size differs from query size")
        size = inferred_size
        observation = aggregate_observation(queries)
    else:
        if size is None:
            raise ValueError("size is required for an empty query family")
        observation = tuple(() for _ in range(size))

    gauge = orbit_partition(size, generators)
    fibers = label_partition(observation)
    orbit_index = {
        item: block_index
        for block_index, block in enumerate(gauge)
        for item in block
    }

    gauge_splits = []
    unseparated = []
    for left, right in combinations(range(size), 2):
        same_gauge_orbit = orbit_index[left] == orbit_index[right]
        same_observation = observation[left] == observation[right]
        if same_gauge_orbit and not same_observation:
            gauge_splits.append((left, right))
        if not same_gauge_orbit and same_observation:
            unseparated.append((left, right))

    if gauge_splits:
        status = "overdiscriminates_licensed_gauge"
    elif unseparated:
        status = "underidentified"
    else:
        status = "exact_quotient_identification"
    return AccessDiagnostic(
        status=status,
        gauge_orbits=gauge,
        observation_fibers=fibers,
        gauge_split_witnesses=tuple(gauge_splits),
        unseparated_non_gauge_pairs=tuple(unseparated),
    )


def minimum_exact_query_family(
    candidates: Sequence[Labels],
    generators: Sequence[Permutation],
) -> tuple[int, ...] | None:
    if not candidates:
        raise ValueError("candidate registry must be nonempty")
    size = len(candidates[0])
    if any(len(candidate) != size for candidate in candidates):
        raise ValueError("candidate query sizes differ")
    for count in range(len(candidates) + 1):
        for indices in combinations(range(len(candidates)), count):
            diagnostic = diagnose_access(
                [candidates[index] for index in indices],
                generators,
                size=size,
            )
            if diagnostic.status == "exact_quotient_identification":
                return indices
    return None
